-- 제보 종류에 zeropay_fail 을 더한다: "비플페이 결제가 안 됐어요".
--
-- 2026-08-21 에 "뚝섬오징어가 비플페이가 안 되는데 지도에 있다"는 제보를 받고 전수
-- 조사를 했다. 그 가게는 오늘 조회에도 제로페이 가맹점으로 살아 있었다 — 상호·주소·
-- 전화번호가 우리 데이터와 바이트 단위로 같다. 수집기는 원본에 충실했고, 깨진 것은
-- 그 위층 전제였다: "제로페이 가맹점 목록에 있다 = 실제로 결제가 된다".
--
-- 가맹은 등록돼 있는데 QR 을 안 달았거나, 안 받거나, 제로페이가 해지를 반영하지
-- 않은 경우다. 공개 엔드포인트는 가맹 상태 상세도 갱신일도 주지 않아서 **코드로는
-- 탐지할 방법이 없다.** 가게에 가 본 사람만 안다.
--
-- 같은 조사에서 나온 다른 오염(제로페이 목록에서 빠졌는데 우리 파일에 남은 51곳)은
-- 제로페이를 다시 받아 대조하면 기계적으로 잡힌다. 그건 이 종류가 아니라 재검증
-- 잡이 할 일이다. 둘은 원인이 달라 하나로 안 덮인다.
--
-- place_fix 에 섞지 않는 이유: 폐업·이전·가격과 뒤섞이면 "제로페이가 실제로는 안
-- 되는 가게"만 따로 세거나 모아볼 수가 없다. 이 앱의 전제가 얼마나 새는지가 그
-- 숫자다.
ALTER TABLE reports DROP CONSTRAINT IF EXISTS reports_kind_check;
ALTER TABLE reports ADD CONSTRAINT reports_kind_check
  CHECK (kind IN ('place_fix','zeropay_fail','delist','abuse','feature'));
